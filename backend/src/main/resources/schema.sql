-- Esquema de la base de pólizas. Ver docs/DATABASE.md para las convenciones.

CREATE TABLE clientes (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo      VARCHAR(150) NOT NULL,
    documento_identidad  VARCHAR(20)  NOT NULL UNIQUE,
    email                VARCHAR(150) NOT NULL,
    telefono             VARCHAR(30),
    fecha_nacimiento     DATE         NOT NULL,
    fecha_registro       DATE         NOT NULL
);

CREATE TABLE polizas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero            VARCHAR(20)    NOT NULL UNIQUE,
    cliente_id        BIGINT         NOT NULL,
    tipo              VARCHAR(10)    NOT NULL,
    estado            VARCHAR(15)    NOT NULL,
    suma_asegurada    DECIMAL(14, 2) NOT NULL,
    prima_anual       DECIMAL(12, 2) NOT NULL,
    fecha_inicio      DATE           NOT NULL,
    fecha_fin         DATE           NOT NULL,
    motivo_cancelacion VARCHAR(255),
    CONSTRAINT fk_polizas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT ck_polizas_tipo   CHECK (tipo IN ('AUTO', 'HOGAR', 'VIDA')),
    CONSTRAINT ck_polizas_estado CHECK (estado IN ('VIGENTE', 'VENCIDA', 'CANCELADA'))
);

CREATE TABLE siniestros (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    poliza_id         BIGINT         NOT NULL,
    fecha_ocurrencia  DATE           NOT NULL,
    fecha_reporte     DATE           NOT NULL,
    descripcion       VARCHAR(500)   NOT NULL,
    monto_reclamado   DECIMAL(14, 2) NOT NULL,
    estado            VARCHAR(15)    NOT NULL,
    CONSTRAINT fk_siniestros_poliza FOREIGN KEY (poliza_id) REFERENCES polizas (id),
    CONSTRAINT ck_siniestros_estado CHECK (estado IN ('REPORTADO', 'EN_REVISION', 'APROBADO', 'RECHAZADO'))
);

CREATE INDEX ix_polizas_cliente ON polizas (cliente_id);
CREATE INDEX ix_siniestros_poliza ON siniestros (poliza_id);
